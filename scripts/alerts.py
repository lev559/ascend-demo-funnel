"""Daily metric monitoring with anomaly detection (what Mixpanel Alerts would do on a paid plan, done on the export).

  python3 scripts/alerts.py [data/v3/events.parquet]  -> analytics/reports/alerts.md

For every day and metric: baseline = median of the same weekday over the previous 4 weeks, spread = MAD of the
previous 28 days, never below the sampling noise of that day's volume (binomial for rates, Poisson for counts). Robust z = (today − baseline) / (1.4826 × MAD). |z| ≥ 4 with a minimum volume fires an alert.
Metrics are rates, so traffic growth doesn't trigger them; volumes are checked against the same weekday.
"""
import os, sys
import numpy as np
import pandas as pd

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "data", "v3", "events.parquet")
ev = pd.read_parquet(SRC)
ev["day"] = ev.ts.dt.tz_localize(None).dt.floor("D")
web = ev[ev.platform == "web"]


def daily(mask, by=None):
    g = web[mask] if by is None else web[mask & by]
    return g.groupby("day").device.nunique()


lv = daily(web.event == "landing_viewed")
qs = daily(web.event == "quiz_started")
pw_and = daily(web.event == "paywall_viewed", web.os == "Android"); cs_and = daily(web.event == "commitment_signed", web.os == "Android")
pw_ios = daily(web.event == "paywall_viewed", web.os == "iOS"); cs_ios = daily(web.event == "commitment_signed", web.os == "iOS")
ai = web[web.event.isin(["coach_questions_generated", "coach_message_shown", "plan_generated"])].groupby("day")["mode"].apply(lambda s: (s == "fallback").mean())
ai_n = web[web.event.isin(["coach_questions_generated", "coach_message_shown", "plan_generated"])].groupby("day").size()
srv = ev[ev.platform == "server"]
subs = srv[srv.event == "subscription_started"].groupby("day").size()
pws = web[web.event.isin(["paywall_viewed", "downsell_viewed"])].groupby("day").device.nunique()
crisis = srv[srv.event == "crisis_flagged"].groupby("day").size()
sit = daily(web.event == "situation_written")

M = {
    "Visitors": (lv, None, 50),
    "Quiz start rate": (qs / lv, lv, 50),
    "Paywall reach after commitment, iOS": (pw_ios / cs_ios, cs_ios, 8),
    "Paywall reach after commitment, Android": (pw_and / cs_and, cs_and, 8),
    "AI fallback rate": (ai, ai_n, 100),
    "Subscriptions per paywall viewer": (subs / pws, pws, 15),
    "Crisis flags per situation": (crisis.reindex(sit.index).fillna(0) / sit, sit, 50),
}
rows = []
for name, (s, vol, min_vol) in M.items():
    s = s.sort_index().astype(float)
    for day in s.index[28:]:
        hist = s[(s.index < day) & (s.index >= day - pd.Timedelta(days=28))].dropna()
        same_wd = hist[hist.index.dayofweek == day.dayofweek]
        if len(same_wd) < 3 or (vol is not None and vol.get(day, 0) < min_vol): continue
        base = same_wd.median(); mad = np.median(np.abs(hist - hist.median()))
        # sampling-noise floor, so quiet days with a few events can't fire: binomial for rates, Poisson for counts
        pb = max(base, hist.mean())  # pooled rate, so a metric that is usually 0 (crisis flags) gets a real noise floor
        floor = np.sqrt(max(base, 1.0)) if vol is None else np.sqrt(max(pb * (1 - pb), 1 / max(vol.get(day, 1), 1)) / max(vol.get(day, 1), 1))
        z = (s[day] - base) / max(1.4826 * mad, floor)
        if abs(z) >= 4: rows.append({"day": day.date(), "metric": name, "value": s[day], "baseline": base, "z": z})
al = pd.DataFrame(rows)
out = ["# Alerts log (simulated data, June–November 2026)", "",
       "Generated by `scripts/alerts.py`. Rule: robust z-score against the same weekday over the previous 4 weeks, |z| ≥ 4, minimum daily volume per metric.", ""]
if len(al):
    out += ["| Day | Metric | Value | Baseline | z |", "|---|---|---|---|---|"]
    for r in al.itertuples():
        fmt = (lambda v: f"{v:,.0f}") if r.metric == "Visitors" else (lambda v: f"{v:.1%}")
        out.append(f"| {r.day} | {r.metric} | {fmt(r.value)} | {fmt(r.baseline)} | {r.z:+.1f} |")
open(os.path.join(ROOT, "analytics", "reports", "alerts.md"), "w").write("\n".join(out) + "\n")
print(al.to_string() if len(al) else "no alerts")
